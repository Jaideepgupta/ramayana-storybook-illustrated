"""
Build the land silhouette for the journey map (no political borders, by design).

Source: Natural Earth 1:110m countries (public domain), as bundled in the geopandas 0.14 wheel.
All country polygons inside the bounding box are unioned into one landmass, so the map shows only
the coastline of the subcontinent and Sri Lanka - no internal or disputed boundaries.

Output: a JS file that sets window.RAMAYANA_GEO = { bbox, scale, path } in projected SVG units.
The app projects journey coordinates with the same function, so points and land line up.

Usage: python3 pipeline/build_map.py <path/to/naturalearth_lowres.shp> <out.js>
"""
import json
import math
import sys

import shapefile                      # pyshp
from shapely.geometry import box, shape
from shapely.ops import unary_union

LON0, LON1, LAT0, LAT1 = 67.0, 93.0, 5.5, 31.0   # bbox: subcontinent + Sri Lanka
K = 20.0                                          # SVG units per degree latitude
COS = math.cos(math.radians((LAT0 + LAT1) / 2))   # simple equirectangular correction


def project(lon, lat):
    return round((lon - LON0) * COS * K, 1), round((LAT1 - lat) * K, 1)


def ring_path(coords):
    pts = [project(x, y) for x, y in coords]
    return "M" + "L".join(f"{x},{y}" for x, y in pts) + "Z"


def main(shp, out):
    clip = box(LON0, LAT0, LON1, LAT1)
    polys = [shape(s.__geo_interface__) for s in shapefile.Reader(shp).shapes()]
    land = unary_union([p.buffer(0) for p in polys if p.intersects(clip)]).intersection(clip)
    land = land.simplify(0.05, preserve_topology=True)
    parts = getattr(land, "geoms", [land])
    d = "".join(ring_path(p.exterior.coords) for p in parts if p.area > 0.05)
    w, h = project(LON1, LAT0)
    geo = {"bbox": [LON0, LON1, LAT0, LAT1], "k": K, "cos": COS, "width": w, "height": h, "path": d}
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by pipeline/build_map.py from Natural Earth 1:110m (public domain). */\n")
        fh.write("window.RAMAYANA_GEO = " + json.dumps(geo) + ";\n")
    print(f"wrote {out}: {len(parts)} parts, {len(d)} path chars, {w}x{h}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
