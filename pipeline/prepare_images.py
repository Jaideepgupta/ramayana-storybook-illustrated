"""
Prepare illustrations for the storybook and register them in the app.

    python3 pipeline/prepare_images.py <folder-with-your-images> <app-dir>

- Accepts PNG/JPG/WEBP named by slot: cover, k01..k07, e002..e044 (case-insensitive, any extension),
  e.g. "K04.png" or "e040-rama-ravana.jpg" (the slot is the first token of the name).
- Centre-crops to portrait 3:4, resizes to 1200x1600, saves optimised JPG (< ~400 KB) into
  <app>/Packages/<id>/content/img/, and rewrites src/images.js to list exactly what exists.
- Reports unknown names and the required slots that are still missing.
"""
import re
import sys
from pathlib import Path

from PIL import Image

REQUIRED = ["cover"] + [f"k0{i}" for i in range(1, 8)]
KEY_MOMENTS = ["e002", "e004", "e006", "e009", "e010", "e015", "e017", "e019", "e020", "e022", "e023", "e025",
               "e027", "e029", "e030", "e031", "e033", "e035", "e036", "e038", "e039", "e040", "e043", "e044"]
W, H, MAX_BYTES = 1200, 1600, 70_000


def slot_of(name: str):
    m = re.match(r"(cover|k0[1-7]|e0\d\d)\b", name.lower())
    return m.group(1) if m and (m.group(1) in REQUIRED or m.group(1) in KEY_MOMENTS) else None


def fit_whole(im: Image.Image) -> Image.Image:
    """Keep the whole picture (no crop); the app frames it with object-fit: cover."""
    im = im.convert("RGB")
    im.thumbnail((760, 760), Image.LANCZOS)
    return im


def fit_portrait(im: Image.Image) -> Image.Image:
    im = im.convert("RGB")
    target = W / H
    w, h = im.size
    if w / h > target:                       # too wide: crop sides
        nw = int(h * target); left = (w - nw) // 2; im = im.crop((left, 0, left + nw, h))
    else:                                    # too tall: crop top/bottom, keep upper-middle (faces)
        nh = int(w / target); top = max(0, int((h - nh) * 0.35)); im = im.crop((0, top, w, top + nh))
    return im.resize((W, H), Image.LANCZOS)


def main(src_dir: str, app_dir: str) -> None:
    content = next(Path(app_dir).glob("Packages/*/content"))
    img_dir = content / "img"; img_dir.mkdir(exist_ok=True)
    found, unknown = {}, []
    for f in sorted(Path(src_dir).iterdir()):
        if f.suffix.lower() not in {".png", ".jpg", ".jpeg", ".webp"}:
            continue
        slot = slot_of(f.stem)
        if not slot:
            unknown.append(f.name); continue
        out = img_dir / f"{slot}.jpg"
        im = fit_whole(Image.open(f))
        for q in (78, 72, 66, 60, 54):
            im.save(out, "JPEG", quality=q, optimize=True, progressive=True)
            if out.stat().st_size <= MAX_BYTES:
                break
        found[slot] = f"img/{slot}.jpg"
        print(f"  {f.name:40s} -> {out.name}  {out.stat().st_size // 1024} KB")
    # images.js keys: cover, K01..K07, E002.. (the app looks up Kanda/Event ids in upper case)
    entries = ",\n  ".join(f'"{s.upper() if s != "cover" else s}": "{p}"' for s, p in found.items())
    (content / "src" / "images.js").write_text(
        "/* Generated by pipeline/prepare_images.py - lists only images that exist in content/img/. */\n"
        "window.RAMAYANA_IMAGES = {\n  " + entries + "\n};\n", encoding="utf-8")
    missing = [s for s in REQUIRED if s not in found]
    print(f"\n{len(found)} images registered. Missing required: {missing or 'none'}. Unrecognised files: {unknown or 'none'}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
