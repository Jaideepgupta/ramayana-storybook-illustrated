"""
Write the storybook's data as a static JS snapshot (window.RAMAYANA_DATA), loaded by the app with
<script src>, instead of live queryAsync against CSV files packaged in the workbook.

Why: on Tableau Cloud, live data-app queries against packaged CSVs failed with 'internal-error'
(all four versions). The story data is static, curated content with no row-level security, so a
snapshot is acceptable; rebuild + republish when the data changes.

Keys are normalised exactly like the app's live loader (lowercase alphanumerics), so the app's
model() works unchanged. ASCII escapes in the CSVs (Devanagari) are decoded here.
Usage: python3 pipeline/build_snapshot.py <out.js>
"""
import csv
import json
import re
import sys
from pathlib import Path

CUR = Path(__file__).resolve().parent.parent / "data" / "curated"
ALL_TABLES = {"kandas": "Kandas", "events": "Events", "characters": "Characters", "locations": "Locations",
              "participation": "Event_Character_Bridge", "journey": "Journey",
              "relationships": "Relationships", "battles": "Battles", "battleParts": "Battle_Participants"}
# Usage: build_snapshot.py <out.js> [--all]   (default: the 6 story tables; --all adds the explorer tables)
TABLES = {k: v for k, v in ALL_TABLES.items()
          if "--all" in sys.argv or k not in ("relationships", "battles", "battleParts")}


def norm(k):
    return re.sub(r"[^a-z0-9]", "", k.lower())


def decode(v):
    return v.encode("ascii").decode("unicode_escape") if "\\u" in v else v


data = {}
for key, name in TABLES.items():
    with open(CUR / f"{name}.csv", encoding="utf-8") as fh:
        data[key] = [{norm(k): decode(v) for k, v in r.items()} for r in csv.DictReader(fh)]

out = Path(sys.argv[1])
out.write_text("/* Generated by pipeline/build_snapshot.py from data/curated - do not edit. */\n"
               "window.RAMAYANA_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")
print(f"wrote {out}: " + ", ".join(f"{k}={len(v)}" for k, v in data.items()))
